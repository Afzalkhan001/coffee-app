/**
 * Every seeded product declares its diet mark (`Product.diet` is optional only so older data stays
 * valid). India: "vegetarian" means no meat and no egg, so egg items carry `diet: 'egg'` and never the
 * `vegetarian` dietary word. Assumptions are listed in docs/CLIENT_DECISIONS.md (the client confirms).
 */
type ProductSeed = Omit<Product, 'isAvailable' | 'isFeatured' | 'isPopular' | 'allowsInstructions' | 'dietary' | 'prepMinutes' | 'rating' | 'ratingCount' | 'diet'> &
  Required<Pick<Product, 'diet'>> &
  Partial<Pick<Product, 'isAvailable' | 'isFeatured' | 'isPopular' | 'allowsInstructions' | 'dietary' | 'prepMinutes'>>;

/** Deterministic demo rating from the product id. */
function demoRating(id: string): { rating: number; ratingCount: number } {
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return { rating: Math.round((4.4 + (h % 6) / 10) * 10) / 10, ratingCount: 60 + (h % 540) };
}

